// Recording runs the reference signal-cli and needs the sandbox:
//
//	just record-golden
var record = flag.Bool("record", false, "re-record golden transcripts from the reference signal-cli")

const (
	repoRoot     = "../.."
	cliDir       = repoRoot + "/testdata/golden/cli"
	cliGoldenDir = cliDir + "/recorded"
	cliPending   = cliDir + "/PENDING"
	oracleBin    = repoRoot + "/third_party/signal-cli-0.14.7/bin/signal-cli"
)

// loadCLIScenarios reads every testdata/golden/cli/scenarios*.json:
// scenarios.json is hand-written, scenarios-observed.json is generated by
// tools/obs2scenarios from spec/surface/cli/observations.md.
func loadCLIScenarios(t *testing.T) []Scenario {
	t.Helper()
	files, err := filepath.Glob(cliDir + "/scenarios*.json")
	if err != nil || len(files) == 0 {
		t.Fatalf("no scenario files in %s: %v", cliDir, err)
	}
	var all []Scenario
	seen := map[string]string{}
	for _, f := range files {
		scs, err := LoadScenarios(f)
		if err != nil {
			t.Fatal(err)
		}
		for _, sc := range scs {
			if prev, dup := seen[sc.Name]; dup {
				t.Fatalf("scenario %q defined in both %s and %s", sc.Name, prev, f)
			}
			seen[sc.Name] = f
		}
		all = append(all, scs...)
	}
	return all
}

func TestCLIGolden(t *testing.T) {
	scs := loadCLIScenarios(t)
	if *record {
		recordAll(t, scs)
		return
	}

	pending, err := LoadPending(cliPending)
	if err != nil {
		t.Fatal(err)
	}
	for name := range pending {
		if !hasScenario(scs, name) {
			t.Errorf("PENDING lists unknown scenario %q", name)
		}
	}
	checkNoStaleGoldens(t, scs)

	bin := buildSignalCLIGo(t)
	for _, sc := range scs {
		t.Run(sc.Name, func(t *testing.T) {
			t.Parallel()
			g, err := ReadGolden(GoldenPath(cliGoldenDir, sc))
			if err != nil {
				t.Fatalf("no golden transcript (run `just record-golden`): %v", err)
			}
			got, err := Run(context.Background(), bin, sc)
			if err != nil {
				t.Fatal(err)
			}
			d := Diff(g.Result, got)
			switch {
			case d != "" && pending[sc.Name]:
				t.Skipf("pending (listed in testdata/golden/cli/PENDING):\n%s", d)
			case d != "":
				t.Errorf("differs from signal-cli 0.14.7:\n%s", d)
			case pending[sc.Name]:
				t.Errorf("matches the reference now; remove it from testdata/golden/cli/PENDING")
			}
		})
	}
}

// checkNoStaleGoldens fails if a recorded transcript has no scenario, so
// deleting a scenario cannot leave an orphan that nobody replays.
func checkNoStaleGoldens(t *testing.T, scs []Scenario) {
	t.Helper()
	files, _ := filepath.Glob(cliGoldenDir + "/*.json")
	for _, f := range files {
		name := strings.TrimSuffix(filepath.Base(f), ".json")
		if !hasScenario(scs, name) {
			t.Errorf("stale golden %s: no scenario named %q", f, name)
		}
	}
}

func hasScenario(scs []Scenario, name string) bool {
	for _, sc := range scs {
		if sc.Name == name {
			return true
		}
	}
	return false
}

// recordOnly limits re-recording to scenarios whose name matches.
var recordOnly = flag.String("record-only", "", "with -record, only scenarios whose name matches this regexp")

func recordAll(t *testing.T, scs []Scenario) {
	if os.Getenv("SIGNAL_CLI_GO_SANDBOX") != "1" {
		t.Fatal("recording runs the reference binary and must happen inside the sandbox")
	}
	bin, err := filepath.Abs(oracleBin)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(bin); err != nil {
		t.Fatalf("reference signal-cli missing (run `just install-oracle`): %v", err)
	}
	only, err := regexp.Compile(*recordOnly)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(cliGoldenDir, 0o755); err != nil {
		t.Fatal(err)
	}
	ver, _ := exec.Command(bin, "--version").Output()

	// Each run is a JVM start; a few in parallel keeps recording quick
	// without starving the sandbox.
	work := make(chan Scenario)
	var wg sync.WaitGroup
	var mu sync.Mutex
	for range 4 {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for sc := range work {
				res, err := Run(context.Background(), bin, sc)
				mu.Lock()
				switch {
				case err != nil:
					t.Errorf("%s: %v", sc.Name, err)
				case strings.Contains(res.Stderr, "Missing required native library"):
					t.Errorf("%s: the oracle could not load libsignal (sandbox problem, not real behavior):\n%s", sc.Name, res.Stderr)
				default:
					g := Golden{Scenario: sc, Oracle: string(trimNL(ver)), Result: res}
					if err := WriteGolden(GoldenPath(cliGoldenDir, sc), g); err != nil {
						t.Errorf("%s: %v", sc.Name, err)
					} else {
						t.Logf("recorded %s (exit %d)", sc.Name, res.ExitCode)
					}
				}
				mu.Unlock()
			}
		}()
	}
	for _, sc := range scs {
		if only.MatchString(sc.Name) {
			work <- sc
		}
	}
	close(work)
	wg.Wait()
}

func trimNL(b []byte) []byte {
	for len(b) > 0 && (b[len(b)-1] == '\n' || b[len(b)-1] == '\r') {
		b = b[:len(b)-1]
	}
	return b
}

// buildSignalCLIGo compiles the binary under test. The output is named
// signal-cli so usage lines that echo argv[0] can match.
func buildSignalCLIGo(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	if d := os.Getenv("GOTMPDIR"); d != "" {
		var err error
		if dir, err = os.MkdirTemp(d, "difftest-bin-"); err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { os.RemoveAll(dir) })
	}
	bin := filepath.Join(dir, "signal-cli")
	cmd := exec.Command("go", "build", "-o", bin, "../../cmd/signal-cli-go")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("go build: %v\n%s", err, out)
	}
	return bin
}
